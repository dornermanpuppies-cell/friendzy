#!/usr/bin/env node
/**
 * Netlify rewrites for the Expo Router static export.
 *
 * `expo export --platform web` emits one HTML shell per route; dynamic segments
 * become files such as `u/[username].html`. Netlify does not know that `/u/alice`
 * should serve that shell, so after every export this script:
 *   1. copies each dynamic shell to a bracket-free twin (`u/_username_.html`) so the
 *      rewrite target never contains `[` or `]`;
 *   2. writes dist/_redirects with one `200` rewrite per dynamic route, most specific first;
 *   3. copies `+not-found.html` to `404.html`, which Netlify serves for unknown paths.
 *
 *   node scripts/netlify-redirects.mjs [dist] [--write-public]
 *
 * netlify.toml runs it after the export. `--write-public` also refreshes
 * public/_redirects so the repo keeps an up-to-date copy of the rules.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const dist = path.resolve(root, args.find((a) => !a.startsWith('--')) ?? 'dist');
const writePublic = args.includes('--write-public');

if (!fs.existsSync(dist)) {
  console.error(`✖ ${path.relative(root, dist)}/ not found — run "npx expo export --platform web" first.`);
  process.exit(1);
}

function collectHtml(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      // Route groups "(app)" are duplicates of the ungrouped paths; bundles live in _expo/assets.
      if (entry.name.startsWith('(') || entry.name === '_expo' || entry.name === 'assets') continue;
      out.push(...collectHtml(full));
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      out.push(full);
    }
  }
  return out;
}

const dynamicShells = collectHtml(dist)
  .map((file) => path.relative(dist, file).split(path.sep).join('/'))
  .filter((rel) => rel.includes('['));

const rules = new Map();
for (const rel of dynamicShells) {
  let route = `/${rel.replace(/\.html$/, '')}`;
  if (route.endsWith('/index')) route = route.slice(0, -'/index'.length) || '/';
  const segments = route.split('/').filter(Boolean);
  const from = `/${segments
    .map((segment) => {
      const splat = /^\[\.\.\.(.+)\]$/.exec(segment);
      if (splat) return '*';
      const param = /^\[(.+)\]$/.exec(segment);
      return param ? `:${param[1]}` : segment;
    })
    .join('/')}`;
  const twin = rel.replace(/\[\.\.\.(.+?)\]/g, '_$1_').replace(/\[(.+?)\]/g, '_$1_');
  fs.mkdirSync(path.dirname(path.join(dist, twin)), { recursive: true });
  fs.copyFileSync(path.join(dist, rel), path.join(dist, twin));
  if (!rules.has(from)) {
    rules.set(from, {
      from,
      to: `/${twin}`,
      literal: segments.filter((s) => !s.startsWith('[')).length,
      depth: segments.length,
      splat: from.includes('*'),
    });
  }
}

const sorted = [...rules.values()].sort((a, b) => Number(a.splat) - Number(b.splat) || b.literal - a.literal || b.depth - a.depth || a.from.localeCompare(b.from));
const width = Math.max(20, ...sorted.map((r) => r.from.length)) + 2;
const lines = [
  '# Generated by scripts/netlify-redirects.mjs after `expo export` — do not edit by hand.',
  '# Dynamic Expo Router routes are served from their static shell and hydrate client-side.',
  ...sorted.map((r) => `${r.from.padEnd(width)}${r.to}  200`),
  '',
];
const content = lines.join('\n');
fs.writeFileSync(path.join(dist, '_redirects'), content);

const notFound = path.join(dist, '+not-found.html');
if (fs.existsSync(notFound)) fs.copyFileSync(notFound, path.join(dist, '404.html'));

if (writePublic) fs.writeFileSync(path.join(root, 'public', '_redirects'), content);

console.log(`✔ wrote ${path.relative(root, path.join(dist, '_redirects'))} with ${sorted.length} rewrite rule(s)${fs.existsSync(notFound) ? ' + 404.html' : ''}${writePublic ? ' (public/_redirects refreshed)' : ''}`);
for (const r of sorted) console.log(`  ${r.from.padEnd(width)}→ ${r.to}`);
